const express = require('express')
const session = require('express-session')
const MongoStore = require('connect-mongo')
const helmet = require('helmet')
const path = require('node:path')
const { rateLimit } = require('express-rate-limit')
const { ZodError } = require('zod')
const { createModels } = require('./domain/models')
const { PLATFORM_CATALOG } = require('./domain/constants')
const { authRouter } = require('./auth')
const { createApi } = require('./api')
const { backupRouter } = require('./backup')
const { createMetadataService } = require('./metadata')
const { migrateDifficulties } = require('./domain/difficulty')
const { createImageService, imageRouter } = require('./images')
async function createApp({ connection, secret, env = process.env, metadata = createMetadataService(env), images = createImageService(env) }) {
  const app = express(), models = createModels(connection)
  await Promise.all(Object.values(models).map(m => m.init()))
  await migrateDifficulties(models)
  await models.PlatformRecord.bulkWrite(PLATFORM_CATALOG.map(p => ({ updateOne: { filter: { _id: p._id }, update: { $setOnInsert: p }, upsert: true } })))
  const production = env.NODE_ENV === 'production'
  app.disable('x-powered-by')
  if (env.TRUST_PROXY) app.set('trust proxy', Number(env.TRUST_PROXY))
  app.use(helmet({ contentSecurityPolicy: { directives: { imgSrc: ["'self'", 'https:', 'data:', 'blob:'], styleSrc: ["'self'", "'unsafe-inline'"], scriptSrc: ["'self'"], connectSrc: ["'self'"] } }, crossOriginEmbedderPolicy: false, strictTransportSecurity: production ? undefined : false }))
  app.use(express.json({ limit: '10mb' }))
  const sessionStore = MongoStore.create({ client: connection.getClient(), dbName: connection.name, collectionName: 'sessions', stringify: false, ttl: 7 * 86400 })
  app.use(session({ name: 'gamelog.sid', secret, store: sessionStore, resave: false, saveUninitialized: false, cookie: { httpOnly: true, sameSite: 'lax', secure: production, maxAge: 7 * 86400000 } }))
  app.get('/api/health', (req, res) => res.status(connection.readyState === 1 ? 200 : 503).json({ status: connection.readyState === 1 ? 'ok' : 'unavailable' }))
  app.use('/api', rateLimit({ windowMs: 60000, limit: env.NODE_ENV === 'test' ? 10000 : 500, standardHeaders: 'draft-7', legacyHeaders: false, message: { error: 'Too many requests. Please wait a moment.' } }))
  app.use('/api', (req, res, next) => {
    if (connection.readyState !== 1) return res.status(503).json({ error: 'Database is unavailable. Your changes have not been saved.' })
    if (['GET', 'HEAD', 'OPTIONS'].includes(req.method)) return next()
    if (!req.session.csrf || req.get('X-CSRF-Token') !== req.session.csrf) return res.status(403).json({ error: 'Your session changed. Reload the page and try again.' })
    const origin = req.get('Origin'), allowed = [env.SITE_URL, env.SERVER_URL, ...(!production ? [`http://localhost:${env.PORT || 4050}`, `http://127.0.0.1:${env.PORT || 4050}`, 'http://localhost:5040', 'http://127.0.0.1:5040'] : [])].filter(Boolean)
    if (origin && !allowed.includes(origin)) return res.status(403).json({ error: 'Request origin is not allowed' })
    next()
  })
  const auth = authRouter({ models, env, sessionCollection: connection.collection('sessions') })
  app.use('/api/auth', auth.router); app.use('/api', auth.requireUser)
  app.use('/api/images', imageRouter(images))
  app.use('/api/backups', backupRouter(models)); app.use('/api', createApi({ models, metadata, images }))
  app.use('/api', (req, res) => res.status(404).json({ error: 'API route not found' }))
  if (production) { const dist = path.join(__dirname, '..', 'client', 'dist'); app.use(express.static(dist)); app.get('*', (req, res) => res.sendFile(path.join(dist, 'index.html'))) }
  app.use((error, req, res, next) => {
    if (error instanceof ZodError) return res.status(400).json({ error: error.issues.map(i => `${i.path.join('.') ? `${i.path.join('.')}: ` : ''}${i.message}`).slice(0, 5).join('; ') })
    if (error.code === 11000) return res.status(409).json({ error: req.path.includes('auth') ? 'An account with that email already exists' : 'This hunt already exists. Use a different edition/list label for a separate trophy list.' })
    if (error.name === 'VersionError') return res.status(409).json({ error: 'This record changed in another window. Reload and try again.' })
    if (error.type === 'entity.too.large') return res.status(413).json({ error: 'This file is too large (maximum 10 MB)' })
    if (error instanceof SyntaxError && error.status === 400) return res.status(400).json({ error: 'Invalid JSON' })
    if (error.status) return res.status(error.status).json({ error: error.message })
    console.error('Request failed:', error.name); res.status(500).json({ error: 'Something went wrong. Your changes may not have been saved; reload before retrying.' })
  })
  return { app, models, sessionStore }
}
module.exports = { createApp }
